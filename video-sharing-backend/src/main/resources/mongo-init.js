// MongoDB initialization for the video sharing comment content KV layer.
// Usage:
//   mongosh "mongodb://root:root@localhost:27017/admin" mongo-init.js
// or mount this file into /docker-entrypoint-initdb.d/ for a MongoDB container.

var databaseName = "video_sharing";
var dbRef = db.getSiblingDB(databaseName);

var commentContentsValidator = {
  $jsonSchema: {
    bsonType: "object",
    required: ["_id", "username", "content", "createdAt", "updatedAt"],
    additionalProperties: true,
    properties: {
      _id: {
        bsonType: ["long", "int", "decimal"],
        description: "Snowflake commentId generated by the backend"
      },
      username: {
        bsonType: "string",
        description: "Snapshot display name at comment creation time"
      },
      content: {
        bsonType: "string",
        minLength: 1,
        maxLength: 1000,
        description: "Comment body"
      },
      contentType: {
        bsonType: ["string", "null"],
        description: "Optional MIME-style content type, for example text/plain"
      },
      mentions: {
        bsonType: ["array", "null"],
        items: { bsonType: "string" },
        description: "Optional mentioned usernames or identifiers"
      },
      attachments: {
        bsonType: ["array", "null"],
        items: { bsonType: "string" },
        description: "Optional attachment object keys or URLs"
      },
      contentVersion: {
        bsonType: ["int", "null"],
        minimum: 1,
        description: "Optional content schema version"
      },
      createdAt: {
        bsonType: "date",
        description: "Creation timestamp"
      },
      updatedAt: {
        bsonType: "date",
        description: "Last update timestamp"
      }
    }
  }
};

var collectionName = "comment_contents";
var collectionOptions = {
  validator: commentContentsValidator,
  validationLevel: "moderate",
  validationAction: "error"
};

if (dbRef.getCollectionNames().indexOf(collectionName) < 0) {
  dbRef.createCollection(collectionName, collectionOptions);
} else {
  dbRef.runCommand({
    collMod: collectionName,
    validator: commentContentsValidator,
    validationLevel: "moderate",
    validationAction: "error"
  });
}

dbRef.comment_contents.createIndex(
  { createdAt: -1, _id: -1 },
  { name: "idx_comment_contents_created_at" }
);

dbRef.comment_contents.createIndex(
  { updatedAt: -1 },
  { name: "idx_comment_contents_updated_at" }
);

print("MongoDB initialization complete for " + databaseName + "." + collectionName);
