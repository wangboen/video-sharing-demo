package com.videosharing.videosharingspringboot.config;

import com.videosharing.videosharingspringboot.model.Video;
import jakarta.persistence.Column;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.dao.DataIntegrityViolationException;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertThrows;

class LegacyVideoVersionMigrationTest {
    private JdbcTemplate jdbc;
    private LegacyVideoVersionMigration migration;

    @BeforeEach
    void setUp() {
        DriverManagerDataSource dataSource = new DriverManagerDataSource(
                "jdbc:h2:mem:video-version-" + System.nanoTime() + ";DB_CLOSE_DELAY=-1", "sa", "");
        jdbc = new JdbcTemplate(dataSource);
        jdbc.execute("""
                create table videos (
                    id bigint generated by default as identity primary key,
                    title varchar(255) not null,
                    version bigint null
                )
                """);
        migration = new LegacyVideoVersionMigration(jdbc, dataSource);
    }

    @Test
    void backfillsNullVersionsPreservesExistingValuesAndEnforcesDefaultNotNull() {
        jdbc.update("insert into videos(title, version) values (?, null)", "legacy");
        jdbc.update("insert into videos(title, version) values (?, ?)", "current", 7L);

        migration.run();

        assertEquals(0L, version("legacy"));
        assertEquals(7L, version("current"));
        jdbc.update("insert into videos(title) values (?)", "defaulted");
        assertEquals(0L, version("defaulted"));
        assertThrows(DataIntegrityViolationException.class,
                () -> jdbc.update("insert into videos(title, version) values (?, null)", "invalid"));
    }

    @Test
    void realH2LegacySchemaMigrationIsIdempotent() {
        jdbc.update("insert into videos(title, version) values (?, null)", "legacy");

        migration.run();
        migration.run();

        assertEquals(0L, version("legacy"));
        assertEquals(1, jdbc.queryForObject("select count(*) from videos", Integer.class));
    }

    @Test
    void productionMySqlStatementsSetDefaultBeforeNotNull() {
        assertEquals(
                "alter table videos alter column version set default 0",
                LegacyVideoVersionMigration.statementsFor("MySQL").get(0));
        assertEquals(
                "alter table videos modify column version bigint not null default 0",
                LegacyVideoVersionMigration.statementsFor("MySQL").get(1));
    }

    @Test
    void optimisticVersionMappingRemainsNonNullAfterMigration() throws Exception {
        Column column = Video.class.getDeclaredField("version").getAnnotation(Column.class);

        assertNotNull(column);
        assertFalse(column.nullable());
    }

    private Long version(String title) {
        return jdbc.queryForObject("select version from videos where title = ?", Long.class, title);
    }
}
