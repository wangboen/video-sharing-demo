package com.videosharing.videosharingspringboot.config;

import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.dao.DataIntegrityViolationException;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertThrows;

class LegacyUserRoleMigrationTest {
    private JdbcTemplate jdbc;
    private LegacyUserRoleMigration migration;

    @BeforeEach
    void setUp() {
        DriverManagerDataSource dataSource = new DriverManagerDataSource(
                "jdbc:h2:mem:role-migration-" + System.nanoTime() + ";DB_CLOSE_DELAY=-1", "sa", "");
        jdbc = new JdbcTemplate(dataSource);
        jdbc.execute("""
                create table users (
                    id bigint generated by default as identity primary key,
                    username varchar(50) not null,
                    role varchar(20) null
                )
                """);
        migration = new LegacyUserRoleMigration(jdbc, dataSource);
    }

    @Test
    void backfillsOnlyNullLegacyRolesAndEnforcesNotNull() {
        jdbc.update("insert into users(username, role) values (?, null)", "legacy");
        jdbc.update("insert into users(username, role) values (?, ?)", "reviewer", "REVIEWER");

        migration.run();

        assertEquals("USER", role("legacy"));
        assertEquals("REVIEWER", role("reviewer"));
        assertThrows(DataIntegrityViolationException.class,
                () -> jdbc.update("insert into users(username, role) values (?, null)", "invalid"));
    }

    @Test
    void rerunIsIdempotent() {
        jdbc.update("insert into users(username, role) values (?, null)", "legacy");

        migration.run();
        migration.run();

        assertEquals("USER", role("legacy"));
        assertEquals(1, jdbc.queryForObject("select count(*) from users", Integer.class));
    }

    private String role(String username) {
        return jdbc.queryForObject("select role from users where username = ?", String.class, username);
    }
}
