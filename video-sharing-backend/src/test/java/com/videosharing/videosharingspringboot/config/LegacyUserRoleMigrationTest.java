package com.videosharing.videosharingspringboot.config;

import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertThrows;

class LegacyUserRoleMigrationTest {
    private JdbcTemplate jdbc;
    private LegacyUserRoleMigration migration;

    @BeforeEach
    void setUp() {
        DriverManagerDataSource dataSource = new DriverManagerDataSource(
                "jdbc:h2:mem:role-migration-" + System.nanoTime() + ";DB_CLOSE_DELAY=-1", "sa", "");
        jdbc = new JdbcTemplate(dataSource);
        jdbc.execute("""
                create table users (
                    id bigint generated by default as identity primary key,
                    username varchar(50) not null,
                    password varchar(255) not null default 'encoded',
                    email varchar(100),
                    role varchar(20) null,
                    created_at timestamp default current_timestamp,
                    updated_at timestamp default current_timestamp
                )
                """);
        jdbc.execute("""
                create table staff_accounts (
                    id bigint primary key,
                    username varchar(50) not null unique,
                    password varchar(255) not null,
                    email varchar(100),
                    role varchar(20) not null,
                    created_at timestamp,
                    updated_at timestamp
                )
                """);
        migration = new LegacyUserRoleMigration(jdbc, dataSource);
    }

    @Test
    void copiesLegacyStaffRowsIntoStaffAccountsWhenRoleColumnExists() {
        jdbc.update("insert into users(username, role) values (?, null)", "legacy");
        jdbc.update("insert into users(username, role) values (?, ?)", "reviewer", "REVIEWER");
        jdbc.update("insert into users(username, role) values (?, ?)", "admin", "ADMIN");

        migration.run();

        assertEquals("USER", role("legacy"));
        assertEquals("REVIEWER", staffRole("reviewer"));
        assertEquals("ADMIN", staffRole("admin"));
    }

    @Test
    void rerunIsIdempotent() {
        jdbc.update("insert into users(username, role) values (?, ?)", "reviewer", "REVIEWER");

        migration.run();
        migration.run();

        assertEquals(1, jdbc.queryForObject("select count(*) from staff_accounts", Integer.class));
    }

    @Test
    void freshSeparatedSchemaWithoutUserRoleColumnIsSkipped() {
        DriverManagerDataSource dataSource = new DriverManagerDataSource(
                "jdbc:h2:mem:fresh-role-migration-" + System.nanoTime() + ";DB_CLOSE_DELAY=-1", "sa", "");
        JdbcTemplate fresh = new JdbcTemplate(dataSource);
        fresh.execute("""
                create table users (
                    id bigint generated by default as identity primary key,
                    username varchar(50) not null,
                    password varchar(255) not null,
                    email varchar(100)
                )
                """);

        new LegacyUserRoleMigration(fresh, dataSource).run();

        assertEquals(0, fresh.queryForObject("select count(*) from users", Integer.class));
    }

    private String role(String username) {
        return jdbc.queryForObject("select role from users where username = ?", String.class, username);
    }

    private String staffRole(String username) {
        return jdbc.queryForObject("select role from staff_accounts where username = ?", String.class, username);
    }
}
